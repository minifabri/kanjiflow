# Genera migration.sql (SQLite e PostgreSQL) secondo le convenzioni di Prisma, a partire da schema.prisma.
import re, sys, os
schema = open(sys.argv[1]).read()
models = {}
order = []
for m in re.finditer(r'model (\w+) \{(.*?)\n\}', schema, re.S):
    name, body = m.group(1), m.group(2)
    order.append(name)
    fields, attrs = [], []
    for line in body.split('\n'):
        line = line.split('//')[0].strip()
        if not line: continue
        if line.startswith('@@'): attrs.append(line); continue
        parts = line.split(None, 2)
        fname, ftype = parts[0], parts[1]
        rest = parts[2] if len(parts) > 2 else ''
        fields.append((fname, ftype, rest))
    models[name] = (fields, attrs)
scalars = {'String','Int','Boolean','DateTime','Float'}
def cols(name):
    out=[]
    for f,t,rest in models[name][0]:
        base=t.rstrip('?[]')
        if base not in scalars: continue
        out.append((f, base, t.endswith('?'), rest))
    return out
def default(rest, dialect):
    m=re.search(r'@default\((.*?)\)(?=\s|$)', rest)
    if not m: return None
    v=m.group(1)
    if v=='now()': return 'CURRENT_TIMESTAMP'
    if v in ('cuid()','uuid()'): return None
    if v in ('true','false'): return v
    if v.startswith('"'): return "'"+v.strip('"').replace("'","''")+"'"
    return v
def typ(base, dialect):
    if dialect=='sqlite': return {'String':'TEXT','Int':'INTEGER','Boolean':'BOOLEAN','DateTime':'DATETIME','Float':'REAL'}[base]
    return {'String':'TEXT','Int':'INTEGER','Boolean':'BOOLEAN','DateTime':'TIMESTAMP(3)','Float':'DOUBLE PRECISION'}[base]
def rels(name):
    out=[]
    for f,t,rest in models[name][0]:
        m=re.search(r'@relation\((.*)\)', rest)
        if not m or 'fields:' not in m.group(1): continue
        args=m.group(1)
        fr=re.search(r'fields: \[(.*?)\]',args).group(1).split(', ')
        to=re.search(r'references: \[(.*?)\]',args).group(1).split(', ')
        od=re.search(r'onDelete: (\w+)',args)
        optional=t.endswith('?')
        ondel={'Cascade':'CASCADE','SetNull':'SET NULL','Restrict':'RESTRICT','NoAction':'NO ACTION'}[od.group(1)] if od else ('SET NULL' if optional else 'RESTRICT')
        out.append((fr, t.rstrip('?'), to, ondel))
    return out
def pk(name):
    for f,t,rest in models[name][0]:
        if '@id' in rest.split(): return [f]
    for a in models[name][1]:
        m=re.match(r'@@id\(\[(.*?)\]\)',a)
        if m: return m.group(1).split(', ')
def indexes(name):
    out=[]
    for f,t,rest in models[name][0]:
        if '@unique' in rest.split(): out.append(('unique',[f]))
    for a in models[name][1]:
        m=re.match(r'@@(unique|index)\(\[(.*?)\]\)',a)
        if m: out.append((m.group(1),m.group(2).split(', ')))
    return out
q=lambda xs: ', '.join('"%s"'%x for x in xs)
def gen(dialect):
    sql=[]; fks=[]
    for name in order:
        p=pk(name)
        lines=[]
        for f,base,opt,rest in cols(name):
            l='    "%s" %s'%(f,typ(base,dialect))
            if not opt: l+=' NOT NULL'
            if dialect=='sqlite' and p==[f]: l+=' PRIMARY KEY'
            d=default(rest,dialect)
            if d is not None: l+=' DEFAULT '+d
            lines.append(l)
        if dialect=='sqlite':
            if len(p)>1: lines.append('\n    PRIMARY KEY (%s)'%q(p))
            for fr,tgt,to,ondel in rels(name):
                lines.append('    CONSTRAINT "%s_%s_fkey" FOREIGN KEY (%s) REFERENCES "%s" (%s) ON DELETE %s ON UPDATE CASCADE'%(name,'_'.join(fr),q(fr),tgt,q(to),ondel))
        else:
            lines.append('\n    CONSTRAINT "%s_pkey" PRIMARY KEY (%s)'%(name,q(p)))
            for fr,tgt,to,ondel in rels(name):
                fks.append('-- AddForeignKey\nALTER TABLE "%s" ADD CONSTRAINT "%s_%s_fkey" FOREIGN KEY (%s) REFERENCES "%s"(%s) ON DELETE %s ON UPDATE CASCADE;'%(name,name,'_'.join(fr),q(fr),tgt,q(to),ondel))
        body=',\n'.join(lines).replace(',\n\n',',\n\n')
        sql.append('-- CreateTable\nCREATE TABLE "%s" (\n%s\n);'%(name,body))
    for name in order:
        for kind,fs in indexes(name):
            suffix='key' if kind=='unique' else 'idx'
            base='%s_%s'%(name,'_'.join(fs))
            # PostgreSQL limita gli identificatori a 63 caratteri: Prisma tronca la parte dei campi e mantiene il suffisso.
            if dialect=='postgresql' and len(base)+len(suffix)+1>63: base=base[:63-len(suffix)-1]
            sql.append('-- CreateIndex\nCREATE %sINDEX "%s_%s" ON "%s"(%s);'%('UNIQUE ' if kind=='unique' else '',base,suffix,name,q(fs)))
    sql+=fks
    return '\n\n'.join(sql)+'\n'
for dialect,path in (('sqlite',sys.argv[2]),('postgresql',sys.argv[3])):
    os.makedirs(path,exist_ok=True)
    open(os.path.join(path,'migration.sql'),'w').write(gen(dialect))
    lock=os.path.join(os.path.dirname(path),'migration_lock.toml')
    open(lock,'w').write('# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "%s"\n'%dialect)
print('ok')
